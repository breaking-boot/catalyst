#!/usr/bin/env node
// Builds the published learner list and the bundled Observed-board seed from
// one exported list, so the two always hold the same data.
//
//   node scripts/build-observed-seed.mjs <export.json>
//       Rebuild data/observed-learners.json AND bootdev-extension/src/alltime-seed.js
//       from a list exported on Catalyst's options page (Top Observed Learners ->
//       Export learners).
//   node scripts/build-observed-seed.mjs
//       Rebuild alltime-seed.js from the current data/observed-learners.json.
//
// The input is read with the extension's own parser (observed-learners.js), so
// a file the extension would refuse is refused here, and whatever the parser
// skips never reaches the repository.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const MODULE = new URL("../bootdev-extension/src/observed-learners.js", import.meta.url);
const DATA_FILE = new URL("../data/observed-learners.json", import.meta.url);
const SEED_FILE = new URL("../bootdev-extension/src/alltime-seed.js", import.meta.url);

const hook = {};
const sandbox = { window: { __BOOTDEV_ENHANCER_TEST__: hook }, Date, JSON, Math, Number, Array, Map, String };
vm.createContext(sandbox);
vm.runInContext(readFileSync(MODULE, "utf8"), sandbox, { filename: fileURLToPath(MODULE) });
const L = hook.observedLearners;

function fail(message) {
  console.error(`build-observed-seed: ${message}`);
  process.exit(1);
}

function readList(url) {
  let text;
  try {
    text = readFileSync(url, "utf8");
  } catch (err) {
    fail(`cannot read ${fileURLToPath(url)}: ${err.message}`);
  }
  const parsed = L.parseObservedLearners(text);
  if (parsed.error) fail(`${fileURLToPath(url)}: ${parsed.error}`);
  return parsed;
}

function seedSource(listJson) {
  return [
    "// alltime-seed.js",
    "// GENERATED by scripts/build-observed-seed.mjs from data/observed-learners.json.",
    "// Do not hand-edit: change the data file or re-export, then re-run the script.",
    "//",
    "// The Observed board's bundled seed: handles and lifetime XP only, in the",
    "// format observed-learners.js reads. A content script rather than a JSON",
    "// asset: a content script cannot fetch an extension URL without a",
    "// web_accessible_resources entry, and that read would be async. This file is",
    "// in scope synchronously, which is what lets a fresh install draw the board",
    "// with no network round-trip at all.",
    "",
    `const ALLTIME_SEED = ${listJson.trim()};`,
    "",
  ].join("\n");
}

const input = process.argv[2];
let listJson;
if (input) {
  const parsed = readList(new URL(input, `file://${process.cwd()}/`));
  const list = L.buildObservedLearners(parsed.learners, parsed.generatedAt ?? Date.now());
  listJson = L.stringifyObservedLearners(list);
  writeFileSync(DATA_FILE, listJson);
  console.log(`wrote data/observed-learners.json (${list.learners.length} learners` +
    `${parsed.skipped ? `, ${parsed.skipped} malformed rows skipped` : ""})`);
} else {
  readList(DATA_FILE); // refuse to build a seed from a file the extension would refuse
  listJson = readFileSync(DATA_FILE, "utf8");
}

writeFileSync(SEED_FILE, seedSource(listJson));
console.log("wrote bootdev-extension/src/alltime-seed.js");
